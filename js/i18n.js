export class I18nManager {
    constructor(translations, defaultLang = 'es', storageKey = 'shel-lang') {
        this.translations = translations;
        this.languages = Object.keys(translations);
        this.currentLang = defaultLang;
        this.storageKey = storageKey;
        this.init();
    }

    init() {
        try {
            const saved = localStorage.getItem(this.storageKey);
            if (saved && this.languages.includes(saved)) {
                this.currentLang = saved;
            }
        } catch (e) {}
        this.updateDOM();
    }

    setLanguage(lang) {
        if (!this.translations[lang]) return;
        this.currentLang = lang;
        this.updateDOM();
        document.documentElement.lang = lang;
        try { localStorage.setItem(this.storageKey, lang); } catch (e) {}
    }
    
    nextLanguage() {
        const idx = this.languages.indexOf(this.currentLang);
        const nextIdx = (idx + 1) % this.languages.length;
        this.setLanguage(this.languages[nextIdx]);
    }

    t(key) {
        return this.translations[this.currentLang]?.[key] || key;
    }

    updateDOM() {
        document.documentElement.lang = this.currentLang;
        document.body.classList.remove(...this.languages.map(l => `lang-${l}`));
        document.body.classList.add(`lang-${this.currentLang}`);

        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = this.t(key);
            if (translation !== key) {
                if (String(translation).includes('<')) {
                    el.innerHTML = translation.replace(/\n/g, '<br>');
                } else if (el.children.length > 0 && el.childNodes.length > 0 && el.childNodes[0].nodeType === 3) {
                    el.childNodes[0].nodeValue = translation + ' ';
                } else if (el.children.length === 0) {
                    el.textContent = translation;
                }
            }
        });

        document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
            const key = el.getAttribute('data-i18n-aria-label');
            const translation = this.t(key);
            if (translation !== key) el.setAttribute('aria-label', translation);
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            const translation = this.t(key);
            if (translation !== key) el.setAttribute('placeholder', translation);
        });
    }
}

